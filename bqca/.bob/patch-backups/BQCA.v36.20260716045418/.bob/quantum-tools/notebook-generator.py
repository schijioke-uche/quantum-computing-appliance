#!/usr/bin/env python3
"""BQCA deterministic Python-to-Jupyter-notebook generator.

Uses only the Python standard library. The .py file remains authoritative.
Cells are split on PEP-style ``# %%`` markers when present; otherwise the source
is stored in one code cell. A leading module docstring is also reflected in the
introductory Markdown cell through the source filename/title metadata.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys
from typing import Any

NBFORMAT = 4
NBFORMAT_MINOR = 5


def source_lines(text: str) -> list[str]:
    lines = text.splitlines(keepends=True)
    if text and not text.endswith(("\n", "\r")):
        lines[-1] += "\n"
    return lines


def split_cells(text: str) -> list[dict[str, Any]]:
    lines = source_lines(text)
    cells: list[dict[str, Any]] = []
    current: list[str] = []
    current_type = "code"

    def flush() -> None:
        nonlocal current
        if not current:
            return
        if current_type == "markdown":
            cleaned = []
            for line in current:
                if line.startswith("# "):
                    cleaned.append(line[2:])
                elif line.startswith("#"):
                    cleaned.append(line[1:].lstrip())
                else:
                    cleaned.append(line)
            cells.append({"cell_type": "markdown", "metadata": {}, "source": cleaned})
        else:
            cells.append(
                {
                    "cell_type": "code",
                    "execution_count": None,
                    "metadata": {},
                    "outputs": [],
                    "source": current,
                }
            )
        current = []

    for line in lines:
        stripped = line.strip()
        if stripped.startswith("# %%"):
            flush()
            current_type = "markdown" if "[markdown]" in stripped.lower() else "code"
            continue
        current.append(line)
    flush()

    if not cells:
        cells.append(
            {
                "cell_type": "code",
                "execution_count": None,
                "metadata": {},
                "outputs": [],
                "source": [],
            }
        )
    return cells


def make_notebook(source_path: pathlib.Path, title: str | None) -> dict[str, Any]:
    text = source_path.read_text(encoding="utf-8")
    resolved_title = title or source_path.stem.replace("-", " ").replace("_", " ").title()
    intro = {
        "cell_type": "markdown",
        "metadata": {},
        "source": [
            f"# {resolved_title}\n",
            "\n",
            f"Automatically generated by BQCA from `{source_path.name}`.\n",
            "\n",
            "The Python source file is the authoritative implementation artifact.\n",
        ],
    }
    return {
        "cells": [intro, *split_cells(text)],
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3",
                "language": "python",
                "name": "python3",
            },
            "language_info": {
                "name": "python",
                "pygments_lexer": "ipython3",
                "codemirror_mode": {"name": "ipython", "version": 3},
                "file_extension": ".py",
                "mimetype": "text/x-python",
                "nbconvert_exporter": "python",
                "version": f"{sys.version_info.major}.{sys.version_info.minor}.{sys.version_info.micro}",
            },
            "bqca": {
                "generator": "notebook-generator.py",
                "policy": "BQCA.v35",
                "source": source_path.name,
            },
        },
        "nbformat": NBFORMAT,
        "nbformat_minor": NBFORMAT_MINOR,
    }


def validate_notebook(path: pathlib.Path) -> None:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except Exception as exc:
        raise ValueError(f"invalid notebook JSON: {exc}") from exc

    if data.get("nbformat") != NBFORMAT:
        raise ValueError(f"unsupported nbformat: {data.get('nbformat')!r}")
    cells = data.get("cells")
    if not isinstance(cells, list) or not cells:
        raise ValueError("notebook must contain at least one cell")
    for index, cell in enumerate(cells):
        if cell.get("cell_type") not in {"markdown", "code", "raw"}:
            raise ValueError(f"cell {index} has invalid cell_type")
        if not isinstance(cell.get("source"), list):
            raise ValueError(f"cell {index} source must be a list of strings")
        if cell.get("cell_type") == "code":
            if "outputs" not in cell or "execution_count" not in cell:
                raise ValueError(f"code cell {index} lacks required execution fields")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate or validate BQCA Jupyter notebooks")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--source", type=pathlib.Path, help="Python source file")
    group.add_argument("--validate", type=pathlib.Path, help="Notebook to validate")
    parser.add_argument("--output", type=pathlib.Path, help="Explicit notebook output path")
    parser.add_argument("--title", help="Notebook title")
    parser.add_argument("--force", action="store_true", help="Overwrite an existing notebook")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    if args.validate:
        path = args.validate.resolve()
        if not path.is_file():
            print(f"BQCA_NOTEBOOK_POLICY=FAIL: file not found: {path}", file=sys.stderr)
            return 2
        try:
            validate_notebook(path)
        except ValueError as exc:
            print(f"BQCA_NOTEBOOK_POLICY=FAIL: {exc}", file=sys.stderr)
            return 3
        print(f"BQCA_NOTEBOOK_POLICY=PASS: {path}")
        return 0

    source = args.source.resolve()
    if not source.is_file():
        print(f"BQCA_NOTEBOOK_GENERATION=FAIL: source not found: {source}", file=sys.stderr)
        return 2
    if source.suffix.lower() != ".py":
        print(f"BQCA_NOTEBOOK_GENERATION=FAIL: source must end with .py: {source}", file=sys.stderr)
        return 2

    output = (args.output.resolve() if args.output else source.with_suffix(".ipynb"))
    if output.exists() and not args.force:
        print(f"BQCA_NOTEBOOK_GENERATION=FAIL: output exists; use --force: {output}", file=sys.stderr)
        return 4

    output.parent.mkdir(parents=True, exist_ok=True)
    notebook = make_notebook(source, args.title)
    temporary = output.with_suffix(output.suffix + ".tmp")
    temporary.write_text(json.dumps(notebook, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    try:
        validate_notebook(temporary)
        temporary.replace(output)
        validate_notebook(output)
    finally:
        if temporary.exists():
            temporary.unlink()

    print(f"BQCA_NOTEBOOK_GENERATION=PASS")
    print(f"SOURCE={source}")
    print(f"NOTEBOOK={output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
