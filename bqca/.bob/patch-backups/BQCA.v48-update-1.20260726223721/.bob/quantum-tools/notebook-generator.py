#!/usr/bin/env python3
"""BQCA deterministic Python-to-Jupyter notebook generator (v37)."""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import sys
from typing import Any

NBFORMAT = 4
NBFORMAT_MINOR = 5


def _lines(text: str) -> list[str]:
    lines = text.splitlines(keepends=True)
    if text and not text.endswith(("\n", "\r")):
        lines[-1] += "\n"
    return lines


def _split_cells(text: str) -> list[dict[str, Any]]:
    source = _lines(text)
    cells: list[dict[str, Any]] = []
    current: list[str] = []
    kind = "code"

    def flush() -> None:
        nonlocal current
        if not current:
            return
        if kind == "markdown":
            cleaned: list[str] = []
            for line in current:
                if line.startswith("# "):
                    cleaned.append(line[2:])
                elif line.startswith("#"):
                    cleaned.append(line[1:].lstrip())
                else:
                    cleaned.append(line)
            cells.append({"cell_type": "markdown", "metadata": {}, "source": cleaned})
        else:
            cells.append({
                "cell_type": "code",
                "execution_count": None,
                "metadata": {},
                "outputs": [],
                "source": current,
            })
        current = []

    for line in source:
        stripped = line.strip()
        if stripped.startswith("# %%"):
            flush()
            kind = "markdown" if "[markdown]" in stripped.lower() else "code"
            continue
        current.append(line)
    flush()
    if not cells:
        cells.append({"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [], "source": []})
    return cells


def source_digest(path: pathlib.Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def make_notebook(source: pathlib.Path, title: str | None) -> dict[str, Any]:
    text = source.read_text(encoding="utf-8")
    resolved_title = title or source.stem.replace("-", " ").replace("_", " ").title()
    digest = source_digest(source)
    intro = {
        "cell_type": "markdown",
        "metadata": {},
        "source": [
            f"# {resolved_title}\n",
            "\n",
            f"Automatically generated by BQCA from `{source.name}`.\n",
            "\n",
            "The Python source file is the authoritative implementation artifact.\n",
        ],
    }
    return {
        "cells": [intro, *_split_cells(text)],
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {
                "name": "python",
                "pygments_lexer": "ipython3",
                "codemirror_mode": {"name": "ipython", "version": 3},
                "file_extension": ".py",
                "mimetype": "text/x-python",
                "nbconvert_exporter": "python",
                "version": f"{sys.version_info.major}.{sys.version_info.minor}.{sys.version_info.micro}",
            },
            "bqca": {
                "generator": "notebook-generator.py",
                "policy": "BQCA.v37",
                "source": source.name,
                "source_sha256": digest,
            },
        },
        "nbformat": NBFORMAT,
        "nbformat_minor": NBFORMAT_MINOR,
    }


def validate_notebook(path: pathlib.Path, source: pathlib.Path | None = None) -> None:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except Exception as exc:
        raise ValueError(f"invalid notebook JSON: {exc}") from exc
    if data.get("nbformat") != NBFORMAT:
        raise ValueError(f"unsupported nbformat: {data.get('nbformat')!r}")
    cells = data.get("cells")
    if not isinstance(cells, list) or not cells:
        raise ValueError("notebook must contain at least one cell")
    for index, cell in enumerate(cells):
        if cell.get("cell_type") not in {"markdown", "code", "raw"}:
            raise ValueError(f"cell {index} has invalid cell_type")
        if not isinstance(cell.get("source"), list):
            raise ValueError(f"cell {index} source must be a list")
        if cell.get("cell_type") == "code" and ("outputs" not in cell or "execution_count" not in cell):
            raise ValueError(f"code cell {index} lacks execution fields")
    if source is not None:
        expected = source_digest(source)
        actual = data.get("metadata", {}).get("bqca", {}).get("source_sha256")
        if actual != expected:
            raise ValueError("notebook source digest does not match Python source")


def main() -> int:
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--source", type=pathlib.Path)
    group.add_argument("--validate", type=pathlib.Path)
    parser.add_argument("--output", type=pathlib.Path)
    parser.add_argument("--title")
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--against-source", type=pathlib.Path)
    args = parser.parse_args()

    if args.validate:
        notebook = args.validate.resolve()
        if not notebook.is_file():
            print(f"BQCA_NOTEBOOK_POLICY=FAIL: file not found: {notebook}", file=sys.stderr)
            return 2
        source = args.against_source.resolve() if args.against_source else None
        try:
            validate_notebook(notebook, source)
        except ValueError as exc:
            print(f"BQCA_NOTEBOOK_POLICY=FAIL: {exc}", file=sys.stderr)
            return 3
        print(f"BQCA_NOTEBOOK_POLICY=PASS: {notebook}")
        return 0

    source = args.source.resolve()
    if not source.is_file() or source.suffix.lower() != ".py":
        print(f"BQCA_NOTEBOOK_GENERATION=FAIL: invalid Python source: {source}", file=sys.stderr)
        return 2
    output = args.output.resolve() if args.output else source.with_suffix(".ipynb")
    if output.exists() and not args.force:
        print(f"BQCA_NOTEBOOK_GENERATION=FAIL: output exists; use --force: {output}", file=sys.stderr)
        return 4

    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = output.with_name(output.name + ".tmp")
    temporary.write_text(json.dumps(make_notebook(source, args.title), indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    try:
        validate_notebook(temporary, source)
        temporary.replace(output)
        validate_notebook(output, source)
    finally:
        if temporary.exists():
            temporary.unlink()

    print("BQCA_NOTEBOOK_GENERATION=PASS")
    print(f"SOURCE={source}")
    print(f"NOTEBOOK={output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

